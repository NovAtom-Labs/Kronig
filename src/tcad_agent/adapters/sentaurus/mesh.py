"""Deterministic Sentaurus Structure Editor script and remote pipeline for 1D specifications.

The reviewed Sentaurus tools used here are 2D/3D. A one-dimensional experiment is
therefore built as a thin slab whose contacts span the full height edges.
Lateral uniformity is verified when the results are exported; the slab is never
presented as a native 1D mesh. Nothing in this module depends on software other
than Sentaurus itself, a POSIX shell and GNU ``timeout`` on the remote host.
"""

from __future__ import annotations

import os
import re
import shlex
from itertools import pairwise

from tcad_agent.domain import geometry2d
from tcad_agent.domain.errors import CapabilityError
from tcad_agent.domain.models import ContactLocation, ExperimentSpec, Region1D, Region2D
from tcad_agent.domain.profiles import BoxProfile

# The slab is as tall as SLAB_ASPECT times the finest requested spacing, within the limits
# below, so triangles stay well shaped from 10 nm junction meshes to sub-nanometre oxides.
SLAB_ASPECT = 100.0
SLAB_MIN_UM = 0.1
SLAB_MAX_UM = 1.0
# Geometric growth of the mesh away from a refined interface (a numerical choice, not physics).
INTERFACE_GROWTH = 1.4
MESH_PREFIX = "n1"
MESH_OUTPUT = f"{MESH_PREFIX}_msh.tdr"
MESH_GENERATION = "sde_unit_slab"
MESH_GENERATION_2D = "sde_2d"
_DOPANT = {"donor": "ArsenicActiveConcentration", "acceptor": "BoronActiveConcentration"}
_MATERIAL = {"silicon": "Silicon", "silicon_dioxide": "Oxide"}
_SAFE = re.compile(r"^[a-z][a-z0-9_-]*$")
_COLORS = ((1, 0, 0), (0, 0, 1), (0, 1, 0), (1, 0, 1))
# Text a FlexNet license failure leaves in Sentaurus output (shell regular expression).
_LICENSE_ERROR = "FlexNet Licensing error|unable to check out"
from tcad_agent.adapters.sentaurus.runtime import ESCALATION_DECKS  # noqa: E402

# Up to about 20 minutes waiting for a free seat, inside the run's own time limit.
LICENSE_WAIT_ATTEMPTS = 40
LICENSE_WAIT_SECONDS = 30


def _number(value: float) -> str:
    return format(value, ".15g")


def region_spacings_um(region: Region1D) -> tuple[float, float]:
    """(coarse, fine) requested spacing of a region in um."""
    extent = region.x1.to("um") - region.x0.to("um")
    target = (
        region.mesh_spacing.to("um") if region.mesh_spacing is not None else max(extent / 50, 1e-3)
    )
    coarse = region.maximum_mesh_spacing.to("um") if region.maximum_mesh_spacing else target
    fine = region.minimum_mesh_spacing.to("um") if region.minimum_mesh_spacing else target
    return coarse, fine


def slab_height_um(spec: ExperimentSpec) -> float:
    finest = min(region_spacings_um(region)[1] for region in spec.regions)
    return min(SLAB_MAX_UM, max(SLAB_MIN_UM, SLAB_ASPECT * finest))


def _um(value: float) -> str:
    return _number(value * 1e6)


def build_sde_script_2d(spec: ExperimentSpec) -> str:
    """Structure, doping, contact and meshing script for a two-dimensional structure.

    The spec's stack axis ``x`` (depth) becomes the editor's second coordinate and its lateral
    axis ``y`` the first, so a vertical cut of the device is exactly the 1D stack.
    """
    for item in (*(r.id for r in spec.regions), *(c.id for c in spec.contacts)):
        if not _SAFE.fullmatch(item):
            raise CapabilityError(f"identifier is not safe for the structure editor: {item!r}")
    regions = [region for region in spec.regions if isinstance(region, Region2D)]
    unsupported = {region.material for region in regions} - set(_MATERIAL)
    if unsupported:
        raise CapabilityError(
            f"the structure builder does not map material(s): {', '.join(sorted(unsupported))}"
        )
    by_id = {region.id: region for region in regions}
    lines = [
        "; Generated by NovAtom TCAD Agent Sentaurus mesh builder (two-dimensional).",
        "; Editor X is the lateral axis (spec y), editor Y the stack axis (spec x).",
        "(sde:clear)",
    ]
    for region in regions:
        x0, x1, y0, y1 = geometry2d.bounds(region)
        lines.append(
            f"(sdegeo:create-rectangle (position {_um(y0)} {_um(x0)} 0) "
            f'(position {_um(y1)} {_um(x1)} 0) "{_MATERIAL[region.material]}" "{region.id}")'
        )
    for index, profile in enumerate(spec.profiles):
        region = by_id[profile.region]
        if region.material != "silicon":
            raise CapabilityError("doping can only be placed in a silicon region")
        dopant = _DOPANT[str(profile.species)]
        concentration = _number(profile.value.to("cm^-3"))
        lines.append(f'(sdedr:define-constant-profile "dop{index}" "{dopant}" {concentration})')
        if isinstance(profile, BoxProfile):
            lines.append(
                f'(sdedr:define-refinement-window "win{index}" "Rectangle" '
                f"(position {_um(profile.y0.to('m'))} {_um(profile.x0.to('m'))} 0) "
                f"(position {_um(profile.y1.to('m'))} {_um(profile.x1.to('m'))} 0))"
            )
            lines.append(
                f'(sdedr:define-constant-profile-placement "dopplace{index}" "dop{index}" '
                f'"win{index}")'
            )
        elif profile.kind == "constant":
            lines.append(
                f'(sdedr:define-constant-profile-region "dopplace{index}" "dop{index}" '
                f'"{profile.region}")'
            )
        else:
            raise CapabilityError("only constant and box doping profiles are mapped")
    corners = {(round(v, 12)) for r in regions for v in geometry2d.bounds(r)}
    for index, contact in enumerate(spec.contacts):
        region = by_id[contact.region]
        start, end, _ = geometry2d.contact_segment(contact, region)
        red, green, blue = _COLORS[index % len(_COLORS)]
        lines.append(
            f'(sdegeo:define-contact-set "{contact.id}" 4 (color:rgb {red} {green} {blue}) "##")'
        )
        # A span narrower than the free edge needs vertices at its ends to own an edge.
        for point in (start, end):
            along = point[1] if str(contact.location) in {"x_min", "x_max"} else point[0]
            if round(along, 12) not in corners:
                lines.append(f"(sdegeo:insert-vertex (position {_um(point[1])} {_um(point[0])} 0))")
        mid = ((start[0] + end[0]) / 2, (start[1] + end[1]) / 2)
        lines.append(
            f"(sdegeo:define-2d-contact (find-edge-id (position {_um(mid[1])} {_um(mid[0])} 0)) "
            f'"{contact.id}")'
        )
    spacings = {region.id: region_spacings_um(region) for region in regions}
    target_of = {
        region.id: (
            region.mesh_spacing.to("um")
            if region.mesh_spacing is not None
            else spacings[region.id][0]
        )
        for region in regions
    }
    for region in regions:
        coarse, fine = spacings[region.id]
        lines.append(
            f'(sdedr:define-refinement-size "ref_{region.id}" {_number(coarse)} {_number(coarse)} '
            f"{_number(fine)} {_number(fine)})"
        )
        lines.append(
            f'(sdedr:define-refinement-region "refplace_{region.id}" "ref_{region.id}" '
            f'"{region.id}")'
        )
    for index, profile in enumerate(spec.profiles):
        if isinstance(profile, BoxProfile):
            coarse, fine = spacings[profile.region]
            lines.append(
                f'(sdedr:define-refinement-size "refbox{index}" '
                f"{_number(target_of[profile.region])} {_number(target_of[profile.region])} "
                f"{_number(fine)} {_number(fine)})"
            )
            lines.append(
                f'(sdedr:define-refinement-placement "refboxplace{index}" "refbox{index}" '
                f'"win{index}")'
            )
    for index, first in enumerate(regions):
        for second in regions[index + 1 :]:
            if geometry2d.shared_edge_length(first, second) <= 0:
                continue
            graded = [
                (spacings[item.id][1], item.id)
                for item in (first, second)
                if spacings[item.id][1] < spacings[item.id][0]
            ]
            if graded:
                value, owner = min(graded)
                lines.append(
                    f'(sdedr:define-refinement-function "ref_{owner}" "MaxLenInt" "{first.id}" '
                    f'"{second.id}" {_number(value)} {_number(INTERFACE_GROWTH)})'
                )
    lines.append(f'(sde:build-mesh "snmesh" "" "{MESH_PREFIX}")')
    return "\n".join(lines) + "\n"


def build_sde_script(spec: ExperimentSpec) -> str:
    """Render the structure, doping, contact and meshing script for ``spec``."""
    if spec.dimension == 2:
        return build_sde_script_2d(spec)
    for item in (*(r.id for r in spec.regions), *(c.id for c in spec.contacts)):
        if not _SAFE.fullmatch(item):
            raise CapabilityError(f"identifier is not safe for the structure editor: {item!r}")
    unsupported = {region.material for region in spec.regions} - set(_MATERIAL)
    if unsupported:
        raise CapabilityError(
            f"the structure builder does not map material(s): {', '.join(sorted(unsupported))}"
        )
    if any(interface.mesh_spacing is not None for interface in spec.interfaces):
        raise CapabilityError("interface mesh spacing is not mapped to the structure builder")
    if spec.mesh_anchors:
        raise CapabilityError("mesh anchors are not mapped to the structure builder")
    ordered = sorted(spec.regions, key=lambda region: region.x0.to("um"))
    for left, right in pairwise(ordered):
        if abs(left.x1.to("um") - right.x0.to("um")) > 1e-9:
            raise CapabilityError("regions must be contiguous along x")
    materials = {region.id: region.material for region in spec.regions}
    height_um = slab_height_um(spec)
    height = _number(height_um)
    lines = [
        "; Generated by NovAtom TCAD Agent Sentaurus mesh builder.",
        f"; One-dimensional experiment as a {height} um tall 2D slab; contacts span full edges.",
        "(sde:clear)",
    ]
    for region in ordered:
        lines.append(
            f"(sdegeo:create-rectangle (position {_number(region.x0.to('um'))} 0 0) "
            f"(position {_number(region.x1.to('um'))} {height} 0) "
            f'"{_MATERIAL[region.material]}" "{region.id}")'
        )
    for index, profile in enumerate(spec.profiles):
        if profile.kind != "constant":
            raise CapabilityError("only constant doping profiles are mapped")
        if materials.get(profile.region) != "silicon":
            raise CapabilityError("doping can only be placed in a silicon region")
        dopant = _DOPANT[str(profile.species)]
        concentration = _number(profile.value.to("cm^-3"))
        lines.append(f'(sdedr:define-constant-profile "dop{index}" "{dopant}" {concentration})')
        lines.append(
            f'(sdedr:define-constant-profile-region "dopplace{index}" "dop{index}" '
            f'"{profile.region}")'
        )
    x_min = min(region.x0.to("um") for region in spec.regions)
    x_max = max(region.x1.to("um") for region in spec.regions)
    for index, contact in enumerate(spec.contacts):
        edge = x_min if contact.location is ContactLocation.X_MIN else x_max
        red, green, blue = _COLORS[index % len(_COLORS)]
        lines.append(
            f'(sdegeo:define-contact-set "{contact.id}" 4 (color:rgb {red} {green} {blue}) "##")'
        )
        lines.append(
            "(sdegeo:define-2d-contact (find-edge-id "
            f'(position {_number(edge)} {_number(height_um / 2)} 0)) "{contact.id}")'
        )
    spacings = {region.id: region_spacings_um(region) for region in ordered}
    for region in ordered:
        coarse, fine = spacings[region.id]
        lines.append(
            f'(sdedr:define-refinement-size "ref_{region.id}" {_number(coarse)} {height} '
            f"{_number(fine)} {height})"
        )
        lines.append(
            f'(sdedr:define-refinement-region "refplace_{region.id}" "ref_{region.id}" '
            f'"{region.id}")'
        )
    for left, right in pairwise(ordered):
        # A region asked to be finer than its coarse spacing is refined where it meets its
        # neighbor and grows away from that interface, as thin inversion layers need.
        graded = [
            (spacings[item.id][1], item.id)
            for item in (left, right)
            if spacings[item.id][1] < spacings[item.id][0]
        ]
        if graded:
            value, owner = min(graded)
            lines.append(
                f'(sdedr:define-refinement-function "ref_{owner}" "MaxLenInt" "{left.id}" '
                f'"{right.id}" {_number(value)} {_number(INTERFACE_GROWTH)})'
            )
    lines.append(f'(sde:build-mesh "snmesh" "" "{MESH_PREFIX}")')
    return "\n".join(lines) + "\n"


def _site_lines() -> list[str]:
    """Optional host-specific setup from the researcher's own environment settings.

    These are the researcher's trusted local configuration (like their SSH login), so a
    setup line may use shell syntax, but it must be a single line.
    """
    lines: list[str] = []
    setup = os.getenv("TCAD_SENTAURUS_SETUP", "").strip()
    if setup:
        if len(setup) > 500 or any(ch in setup for ch in "\r\n\x00"):
            raise CapabilityError("TCAD_SENTAURUS_SETUP must be one line of at most 500 characters")
        lines.append(setup)
    directory = os.getenv("TCAD_SENTAURUS_BIN", "").strip()
    if directory:
        lines.append(f"PATH={shlex.quote(directory)}:$PATH; export PATH")
    license_server = os.getenv("TCAD_SENTAURUS_LICENSE", "").strip()
    if license_server:
        lines.append(f"LM_LICENSE_FILE={shlex.quote(license_server)}; export LM_LICENSE_FILE")
    return lines


def build_run_script() -> str:
    """POSIX pipeline executed under ``timeout``: mesh, then device simulation."""
    site = "".join(f"{line}\n" for line in _site_lines())
    return (
        "#!/bin/sh\n"
        "# Generated by NovAtom TCAD Agent. Requires only Sentaurus, a POSIX shell and timeout.\n"
        f"{site}"
        "for tool in sde sdevice; do\n"
        '  command -v "$tool" > /dev/null 2>&1 || {\n'
        '    echo "Sentaurus tool $tool was not found on the remote PATH" >&2; exit 24; }\n'
        "done\n"
        "# Shared license pools are often exhausted for minutes. Wait for a seat, but only for\n"
        "# that reason, so a real geometry or syntax error still fails at once. The script runs\n"
        "# under the run's own time limit, which bounds the wait.\n"
        "attempt=1\n"
        "while :; do\n"
        "  sde -e -l mesh.scm > sde.stdout.log 2> sde.stderr.log && break\n"
        f'  grep -q -E "{_LICENSE_ERROR}" sde.stdout.log sde.stderr.log || exit 21\n'
        f"  [ $attempt -lt {LICENSE_WAIT_ATTEMPTS} ] || exit 21\n"
        "  attempt=$((attempt + 1))\n"
        f"  sleep {LICENSE_WAIT_SECONDS}\n"
        "done\n"
        f'[ -s {MESH_OUTPUT} ] || {{ echo "structure editor produced no mesh" >&2; exit 22; }}\n'
        f"cp {MESH_OUTPUT} device.tdr || exit 23\n"
        "# The device simulator follows the same license rule. When it gives up on a bias\n"
        "# ramp, the same experiment is rerun with the next prepared numerical strategy,\n"
        "# and the level that produced the results is logged for the report.\n"
        "# A strategy that merely creeps along a bias ramp never gives up by itself, so each one\n"
        "# gets a share of the time left and a timeout counts as a stall.\n"
        "level=0\n"
        'stalled=""\n'
        "budget=${KRONIG_BUDGET_SECONDS:-3000}\n"
        "started=$(date +%s)\n"
        f"for deck in sdevice.cmd {' '.join(ESCALATION_DECKS)}; do\n"
        '  [ -f "$deck" ] || break\n'
        "  if [ $level -gt 0 ]; then\n"
        "    rm -f point_*_des.tdr point_*_circuit_des.sav point_*_sdevice.plt sdevice.tdr \\\n"
        "      sdevice.plt sdevice_*_des.tdr sdevice_*.sav\n"
        "  fi\n"
        "  remaining=$((budget - ($(date +%s) - started) - 60))\n"
        "  [ $remaining -gt 60 ] || remaining=60\n"
        "  case $level in 0) share=35;; 1) share=40;; 2) share=60;; *) share=100;; esac\n"
        "  limit=$((remaining * share / 100))\n"
        "  timedout=0\n"
        "  attempt=1\n"
        "  while :; do\n"
        '    timeout "${limit}s" sdevice "$deck" > sdevice.stdout.log 2> sdevice.stderr.log\n'
        "    status=$?\n"
        "    [ $status -eq 0 ] && break\n"
        "    [ $status -eq 124 ] && { timedout=1; break; }\n"
        f'    grep -q -E "{_LICENSE_ERROR}" sdevice.stdout.log sdevice.stderr.log || exit $status\n'
        f"    [ $attempt -lt {LICENSE_WAIT_ATTEMPTS} ] || exit $status\n"
        "    attempt=$((attempt + 1))\n"
        f"    sleep {LICENSE_WAIT_SECONDS}\n"
        "  done\n"
        '  echo "KRONIG numerics level $level stalled:$stalled" >> sdevice.stdout.log\n'
        "  # A ramp that cannot even re-solve its starting point is skipped without an error exit.\n"
        '  grep -q -E "Step-size less than MinStep|Solve for t=0 does not converge" \\\n'
        "    sdevice.stdout.log && gaveup=1 || gaveup=0\n"
        "  [ $timedout -eq 1 ] || [ $gaveup -eq 1 ] || exit 0\n"
        '  stalled="$stalled $level"\n'
        "  level=$((level + 1))\n"
        "done\n"
        "exit 0\n"
    )
